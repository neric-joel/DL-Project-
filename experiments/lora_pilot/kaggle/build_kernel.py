"""Write kaggle/turbo_lora/{kernel.py, kernel-metadata.json}: a self-contained Kaggle GPU script that
LoRA-fine-tunes whisper-large-v3-turbo with the pilot's recipe and decodes the PriMock57 test windows.

usage: python build_kernel.py REPO_DIR
"""
import base64
import json
import sys
from pathlib import Path

repo, here = Path(sys.argv[1]), Path(__file__).parent
files = {
    "experiments/lora_pilot/train.py": repo / "experiments/lora_pilot/train.py",
    "experiments/lora_pilot/merge.py": repo / "experiments/lora_pilot/merge.py",
    "experiments/lora_pilot/decode_gpu.py": here / "decode_gpu.py",
}
blobs = {k: base64.b64encode(p.read_bytes()).decode() for k, p in files.items()}
DEV = ["day5_consultation04", "day5_consultation07"]
TEST = sys.argv[2].split(",")

kernel = f'''"""Turbo LoRA (CSE 598 DL project, exploratory): train, merge, decode. Generated by build_kernel.py."""
import base64, glob, os, shutil, subprocess, sys, time
T0 = time.time()

def sh(cmd, env=None):
    print(f"\\n$ {{cmd}}  [{{(time.time() - T0) / 60:.1f}} min]", flush=True)
    subprocess.run(["bash", "-c", "set -o pipefail; " + cmd], check=True, env=env)   # a failing step behind tee still stops the run

OUT = "/kaggle/working/out"
REPO = "/kaggle/working/repo"
os.makedirs(OUT, exist_ok=True)
sh("nvidia-smi")
sh(f"git clone -q --depth 1 --branch feature/second-listen-app https://github.com/neric-joel/DL-Project- {{REPO}}")
os.chdir(REPO)
for path, b in {json.dumps(blobs)}.items():
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(base64.b64decode(b))
sh("pip install -q --no-deps -e .")
sh("pip install -q faster-whisper==1.2.1 ctranslate2==4.8.2 whisper-normalizer==0.1.15 jiwer==4.0.0 "
   "RapidFuzz==3.14.6 soundfile==0.14.0 PyYAML==6.0.3 transformers==4.46.3 peft==0.13.2 accelerate==1.1.1")
sh("python -c 'import torch, transformers, peft, ctranslate2, pandas, numpy; "
   "print(torch.__version__, torch.cuda.is_available(), transformers.__version__, peft.__version__, "
   "ctranslate2.__version__, pandas.__version__, numpy.__version__)'")
sh("asrshift download --dataset primock57 > {{OUT}}/download.log 2>&1 || (tail -20 {{OUT}}/download.log; exit 1)".replace("{{OUT}}", OUT))

LORA = OUT + "/turbo_lora"
sh(f"python -u experiments/lora_pilot/train.py --base openai/whisper-large-v3-turbo --out {{LORA}} "
   f"--batch 4 --accum 2 --max-steps 400 --eval-every 25 --patience 3 --save-every 50 --grad-ckpt "
   f"2>&1 | tee {{OUT}}/train.log")
if not os.path.exists(LORA + "/adapter_best/adapter_model.safetensors"):
    sys.exit("training produced no adapter")
sh(f"python -u experiments/lora_pilot/merge.py --base openai/whisper-large-v3-turbo --out {{LORA}} "
   f"--quantization float16 2>&1 | tee {{OUT}}/merge.log")

# CTranslate2 finds cuDNN / cuBLAS through the pip wheels torch already ships
env = dict(os.environ)
libs = glob.glob(os.path.join(os.path.dirname(__import__("torch").__file__), "..", "nvidia", "*", "lib"))
env["LD_LIBRARY_PATH"] = ":".join([os.path.abspath(p) for p in libs] + [env.get("LD_LIBRARY_PATH", "")])
cons = " ".join({json.dumps(DEV + TEST)})
sh(f"python -u experiments/lora_pilot/decode_gpu.py {{LORA}}/ct2_float16 {{OUT}}/turbo_lora.jsonl {{cons}} "
   f"2>&1 | tee {{OUT}}/decode.log", env=env)

# keep the adapter, logs and transcripts; the merged model (about 3 GB) can be rebuilt from the adapter
for d in ("merged", "ct2_float16", "adapter_last"):
    shutil.rmtree(os.path.join(LORA, d), ignore_errors=True)
for f in glob.glob(LORA + "/state.pt"):
    os.remove(f)
sh(f"du -sh {{OUT}}/* {{LORA}}/*")
print(f"all done in {{(time.time() - T0) / 60:.1f}} min", flush=True)
'''
out = here / "turbo_lora"
out.mkdir(exist_ok=True)
(out / "kernel.py").write_text(kernel, encoding="utf-8")
meta = {"id": "harshinibv/dl-project-turbo-lora", "title": "dl-project-turbo-lora", "code_file": "kernel.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_internet": True, "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}
(out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
print("wrote", out, f"({len(kernel) / 1024:.0f} KiB)")
