"""Write kaggle/turbo_lora2/{kernel.py, kernel-metadata.json}: robustness + verifier-data job.

  A. seeds 599 and 600: train turbo LoRA with the same recipe, decode dev + the 47 test consultations' windows
  B. the seed-598 adapter from the first job: decode Eka (all splits), PriMock57 turns (test + recalibration)
     and the recalibration windows, through asrshift.infer.run

usage: python build_kernel2.py REPO_DIR TEST_CONSULTATIONS(comma separated)
"""
import base64
import json
import sys
from pathlib import Path

repo, here = Path(sys.argv[1]), Path(__file__).parent
DECODE_ONLY = "--decode-only" in sys.argv   # part B only (seed-598 decodes)
files = {
    "experiments/lora_pilot/train.py": repo / "experiments/lora_pilot/train.py",
    "experiments/lora_pilot/merge.py": repo / "experiments/lora_pilot/merge.py",
    "experiments/lora_pilot/decode_gpu.py": here / "decode_gpu.py",
    "experiments/lora_pilot/decode_units.py": here / "decode_units.py",
}
blobs = {k: base64.b64encode(p.read_bytes()).decode() for k, p in files.items()}
CONS = ["day5_consultation04", "day5_consultation07"] + sys.argv[2].split(",")
SETS = ["eka_calibration", "eka_validation", "eka_test", "pm_turn_recalibration", "pm_turn_test",
        "pm_window_recalibration"]

kernel = f'''"""Turbo LoRA robustness + verifier data (CSE 598 DL project, exploratory). Generated by build_kernel2.py."""
import base64, glob, os, shutil, subprocess, sys, time
T0 = time.time()

def sh(cmd, env=None, check=True):
    print(f"\\n$ {{cmd}}  [{{(time.time() - T0) / 60:.1f}} min]", flush=True)
    return subprocess.run(["bash", "-c", "set -o pipefail; " + cmd], check=check, env=env).returncode

OUT, REPO = "/kaggle/working/out", "/kaggle/working/repo"
os.makedirs(OUT, exist_ok=True)
sh("nvidia-smi -L; find /kaggle/input -maxdepth 6 | head -40", check=False)   # head closes the pipe early
sh(f"git clone -q --depth 1 --branch feature/second-listen-app https://github.com/neric-joel/DL-Project- {{REPO}}")
os.chdir(REPO)
for path, b in {json.dumps(blobs)}.items():
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(base64.b64decode(b))
sh("pip install -q --no-deps -e .")
sh("pip install -q faster-whisper==1.2.1 ctranslate2==4.8.2 whisper-normalizer==0.1.15 jiwer==4.0.0 "
   "RapidFuzz==3.14.6 av==18.1.0 soundfile==0.14.0 PyYAML==6.0.3 transformers==4.46.3 peft==0.13.2 accelerate==1.1.1")
sh(f"asrshift download > {{OUT}}/download.log 2>&1 || (tail -30 {{OUT}}/download.log; exit 1)")
sh(f"asrshift prepare > {{OUT}}/prepare.log 2>&1 || (tail -30 {{OUT}}/prepare.log; exit 1)")
env = dict(os.environ)
libs = glob.glob(os.path.join(os.path.dirname(__import__("torch").__file__), "..", "nvidia", "*", "lib"))
env["LD_LIBRARY_PATH"] = ":".join([os.path.abspath(p) for p in libs] + [env.get("LD_LIBRARY_PATH", "")])
BASE = "openai/whisper-large-v3-turbo"
cons = " ".join({json.dumps(CONS)})
failed = []

# B first: the seed-598 adapter from the first job (its output is attached as an input)
found = glob.glob("/kaggle/input/**/adapter_best/adapter_model.safetensors", recursive=True)
print("seed-598 adapter:", found, flush=True)
if found:
    d = OUT + "/seed598"
    os.makedirs(d, exist_ok=True)
    shutil.copytree(os.path.dirname(found[0]), d + "/adapter_best", dirs_exist_ok=True)
    if sh(f"python -u experiments/lora_pilot/merge.py --base {{BASE}} --out {{d}} --quantization float16 "
          f"2>&1 | tail -5", check=False) == 0:
        if sh(f"python -u experiments/lora_pilot/decode_units.py {{d}}/ct2_float16 turbo_lora_s598 {{d}}/units.jsonl "
              f"{" ".join(SETS)} 2>&1 | grep -v 'it/s' | tail -20", env=env, check=False):
            failed.append("decode seed598")
        shutil.rmtree(d + "/merged", ignore_errors=True); shutil.rmtree(d + "/ct2_float16", ignore_errors=True)
    else:
        failed.append("merge seed598")
else:
    failed.append("seed-598 adapter not found")

# A: two more seeds, same recipe
for seed in {"()" if DECODE_ONLY else "(599, 600)"}:
    d = f"{{OUT}}/seed{{seed}}"
    rc = sh(f"python -u experiments/lora_pilot/train.py --seed {{seed}} --base {{BASE}} --out {{d}} --batch 4 --accum 2 "
            f"--max-steps 400 --eval-every 25 --patience 3 --save-every 50 --grad-ckpt 2>&1 | tee {{d}}.train.log",
            check=False)
    if rc or not os.path.exists(d + "/adapter_best/adapter_model.safetensors"):
        failed.append(f"train {{seed}}"); continue
    if sh(f"python -u experiments/lora_pilot/merge.py --base {{BASE}} --out {{d}} --quantization float16 2>&1 | tail -3",
          check=False):
        failed.append(f"merge {{seed}}"); continue
    if sh(f"python -u experiments/lora_pilot/decode_gpu.py {{d}}/ct2_float16 {{d}}/windows.jsonl {{cons}} "
          f"2>&1 | tee {{d}}.decode.log", env=env, check=False):
        failed.append(f"decode {{seed}}")
    for x in ("merged", "ct2_float16", "adapter_last"):
        shutil.rmtree(os.path.join(d, x), ignore_errors=True)
    for f in glob.glob(d + "/state.pt"):
        os.remove(f)

sh(f"du -sh {{OUT}}/*", check=False)
print("FAILED STEPS:", failed or "none", flush=True)
print(f"all done in {{(time.time() - T0) / 60:.1f}} min", flush=True)
'''
out = here / ("turbo_lora_decode" if DECODE_ONLY else "turbo_lora2")
out.mkdir(exist_ok=True)
(out / "kernel.py").write_text(kernel, encoding="utf-8")
slug = "dl-project-turbo-lora-decode" if DECODE_ONLY else "dl-project-turbo-lora-robustness"
meta = {"id": f"harshinibv/{slug}", "title": slug,
        "code_file": "kernel.py", "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": True, "dataset_sources": [], "competition_sources": [],
        "kernel_sources": ["harshinibv/dl-project-turbo-lora"], "model_sources": []}
(out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
print("wrote", out, f"({len(kernel) / 1024:.0f} KiB)")
