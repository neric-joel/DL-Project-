"""Write two Kaggle kernels (run in parallel):

  turbo_lora_mixed/  turbo LoRA trained on PriMock57 training consultations + Eka calibration (seed 598),
                     decoded on Eka validation/test and PriMock57 turns + windows (recalibration + test)
  turbo_lora_folds/  4 out-of-fold models with the same recipe, each leaving 2 of the 8 PriMock57 training
                     consultations out and decoding those 2 (turns + windows), for verifier training data

usage: python build_kernel3.py REPO_DIR
"""
import base64
import json
import sys
from pathlib import Path

repo, here = Path(sys.argv[1]), Path(__file__).parent
files = {
    "experiments/lora_pilot/train.py": repo / "experiments/lora_pilot/train.py",
    "experiments/lora_pilot/merge.py": repo / "experiments/lora_pilot/merge.py",
    "experiments/lora_pilot/decode_units.py": here / "decode_units.py",
}
blobs = {k: base64.b64encode(p.read_bytes()).decode() for k, p in files.items()}
FOLDS = [["day1_consultation02", "day1_consultation15"], ["day2_consultation07", "day2_consultation09"],
         ["day3_consultation01", "day3_consultation10"], ["day4_consultation02", "day4_consultation03"]]
ALL_SETS = "eka_validation eka_test pm_turn_recalibration pm_turn_test pm_window_recalibration pm_window_test"
TRAIN = "--batch 4 --accum 2 --max-steps 600 --eval-every 25 --patience 3 --save-every 50 --grad-ckpt --eka"

HEAD = f'''import base64, glob, json, os, shutil, subprocess, sys, time
T0 = time.time()

def sh(cmd, env=None, check=True):
    print(f"\\n$ {{cmd}}  [{{(time.time() - T0) / 60:.1f}} min]", flush=True)
    return subprocess.run(["bash", "-c", "set -o pipefail; " + cmd], check=check, env=env).returncode

OUT, REPO = "/kaggle/working/out", "/kaggle/working/repo"
os.makedirs(OUT, exist_ok=True)
sh("nvidia-smi -L", check=False)
sh(f"git clone -q --depth 1 --branch feature/second-listen-app https://github.com/neric-joel/DL-Project- {{REPO}}")
os.chdir(REPO)
for path, b in {json.dumps(blobs)}.items():
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(base64.b64decode(b))
sh("pip install -q --no-deps -e .")
sh("pip install -q faster-whisper==1.2.1 ctranslate2==4.8.2 whisper-normalizer==0.1.15 jiwer==4.0.0 "
   "RapidFuzz==3.14.6 av==18.1.0 soundfile==0.14.0 PyYAML==6.0.3 transformers==4.46.3 peft==0.13.2 accelerate==1.1.1")
sh(f"asrshift download > {{OUT}}/download.log 2>&1 || (tail -30 {{OUT}}/download.log; exit 1)")
sh(f"asrshift prepare > {{OUT}}/prepare.log 2>&1 || (tail -30 {{OUT}}/prepare.log; exit 1)")
env = dict(os.environ)
libs = glob.glob(os.path.join(os.path.dirname(__import__("torch").__file__), "..", "nvidia", "*", "lib"))
env["LD_LIBRARY_PATH"] = ":".join([os.path.abspath(p) for p in libs] + [env.get("LD_LIBRARY_PATH", "")])
BASE = "openai/whisper-large-v3-turbo"
failed = []

def run(d, holdout, sets, cons=""):
    """train -> merge -> decode `sets` (PriMock57 limited to `cons` if given) into d/units.jsonl"""
    os.makedirs(d, exist_ok=True)
    rc = sh(f"python -u experiments/lora_pilot/train.py --seed 598 --base {{BASE}} --out {{d}} {TRAIN} "
            f"--holdout '{{holdout}}' 2>&1 | grep -v Warning | tee {{d}}/train.log", check=False)
    if rc or not os.path.exists(d + "/adapter_best/adapter_model.safetensors"):
        failed.append(f"train {{d}}"); return
    if sh(f"python -u experiments/lora_pilot/merge.py --base {{BASE}} --out {{d}} --quantization float16 2>&1 | tail -3",
          check=False):
        failed.append(f"merge {{d}}"); return
    e = dict(env, CONS=cons)
    if sh(f"python -u experiments/lora_pilot/decode_units.py {{d}}/ct2_float16 turbo_lora {{d}}/units.jsonl {{sets}} "
          f"2>&1 | grep -v 'it/s' | tail -15", env=e, check=False):
        failed.append(f"decode {{d}}")
    for x in ("merged", "ct2_float16", "adapter_last"):
        shutil.rmtree(os.path.join(d, x), ignore_errors=True)
    for f in glob.glob(d + "/state.pt"):
        os.remove(f)
'''
TAIL = '''
sh(f"du -sh {OUT}/*", check=False)
print("FAILED STEPS:", failed or "none", flush=True)
print(f"all done in {(time.time() - T0) / 60:.1f} min", flush=True)
'''
jobs = {
    "dl-project-turbo-lora-mixed": ("turbo_lora_mixed", f'run(OUT + "/mixed", "", "{ALL_SETS}")\n'),
    "dl-project-turbo-lora-folds": ("turbo_lora_folds", "".join(
        f'run(OUT + "/fold{i}", "{",".join(f)}", "pm_turn_recalibration pm_window_recalibration", "{",".join(f)}")\n'
        for i, f in enumerate(FOLDS))),
}
for slug, (folder, body) in jobs.items():
    out = here / folder
    out.mkdir(exist_ok=True)
    k = f'"""{slug} (CSE 598 DL project, exploratory). Generated by build_kernel3.py."""\n' + HEAD + body + TAIL
    (out / "kernel.py").write_text(k, encoding="utf-8")
    meta = {"id": f"harshinibv/{slug}", "title": slug, "code_file": "kernel.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print("wrote", out, f"({len(k) / 1024:.0f} KiB)")
